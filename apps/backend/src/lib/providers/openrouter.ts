import type { TextProvider, GenerateTextOptions, ImageProvider, VideoProvider } from "./types.js";
import { DashScopeVideoProvider } from "./dashscope.js";
import { downloadAndStoreImageUrl } from "../storage.js";

const OPENROUTER_BASE_URL = "https://openrouter.ai/api/v1";

function getApiKey(): string {
  const key = process.env.OPENROUTER_API_KEY;
  if (!key) throw new Error("OPENROUTER_API_KEY not set");
  return key;
}

export class OpenRouterTextProvider implements TextProvider {
  async generate(options: GenerateTextOptions): Promise<string> {
    const messages: Record<string, unknown>[] = [];
    if (options.system) {
      messages.push({ role: "system", content: options.system });
    }
    messages.push({ role: "user", content: options.prompt });

    const response = await fetch(`${OPENROUTER_BASE_URL}/chat/completions`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${getApiKey()}`,
      },
      body: JSON.stringify({
        model: process.env.AI_TEXT_MODEL ?? "anthropic/claude-3.5-sonnet",
        messages,
        max_tokens: options.maxTokens ?? 8192,
        temperature: options.temperature ?? 0.7,
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(
        `OpenRouter text API error: ${response.status} ${errorText}`,
      );
    }

    const data = (await response.json()) as {
      choices?: { message?: { content: string } }[];
    };
    return data.choices?.[0]?.message?.content ?? "";
  }
}

export class OpenRouterImageProvider implements ImageProvider {
  async generate(
    prompt: string,
    size?: string,
    model?: string,
    options?: { negativePrompt?: string; qualityTags?: string[] },
  ): Promise<string> {
    let finalPrompt = prompt;
    if (options?.qualityTags?.length) {
      finalPrompt += `, ${options.qualityTags.join(", ")}`;
    }

    const body: Record<string, unknown> = {
      model: model ?? process.env.AI_IMAGE_MODEL ?? "google/gemini-2.5-flash-image",
      prompt: finalPrompt,
      n: 1,
    };

    if (size) {
      body.size = size;
    }

    if (options?.negativePrompt) {
      body.negative_prompt = options.negativePrompt;
    }

    const response = await fetch(`${OPENROUTER_BASE_URL}/images/generations`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${getApiKey()}`,
      },
      body: JSON.stringify(body),
    });

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(
        `OpenRouter image API error: ${response.status} ${errorText}`,
      );
    }

    const data = (await response.json()) as {
      data?: { url: string }[];
    };
    const imageUrl = data.data?.[0]?.url;

    if (!imageUrl) {
      throw new Error("No image generated by OpenRouter");
    }

    return downloadAndStoreImageUrl(imageUrl);
  }
}

export class OpenRouterVideoProvider implements VideoProvider {
  private dashScopeVideoProvider = new DashScopeVideoProvider();

  async generate(
    sceneImages: { url: string; description: string }[],
    storyboard: string,
    avatarReferenceImage?: string,
    onProgress?: (completed: number, total: number) => void,
    options?: { avatarReferenceImage?: string; negativePrompt?: string },
  ): Promise<string[]> {
    return this.dashScopeVideoProvider.generate(
      sceneImages,
      storyboard,
      avatarReferenceImage,
      onProgress,
      options,
    );
  }
}
